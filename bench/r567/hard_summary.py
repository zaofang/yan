"""Markdown summary of a hard-suite run: pass rates, repair cost, tokens and sign tests per arm.

usage: uv run python bench/r567/hard_summary.py RUNS_DIR LEDGER [--commit SHA --date YYYY-MM-DD]
RUNS_DIR holds hard-MODEL-sN directories (one per seed).
"""

import argparse
import collections
import json
import pathlib
from math import comb


def sign_p(a: int, b: int) -> float:
    n = a + b
    return 1.0 if n == 0 else min(1.0, 2 * sum(comb(n, i) for i in range(min(a, b) + 1)) / 2**n)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("runs", type=pathlib.Path)
    ap.add_argument("ledger", type=pathlib.Path)
    ap.add_argument("--commit", default="")
    ap.add_argument("--date", default="")
    a = ap.parse_args()
    recs = collections.defaultdict(list)
    for f in sorted(a.runs.glob("hard-*-s*/*.json")):
        r = json.loads(f.read_text())
        r["_seed"] = f.parent.name.rsplit("-", 1)[1]
        recs[f.parent.name.split("-")[1]].append(r)
    print(f"Hard suite, commit {a.commit}, {a.date}. Generated by bench/r567/hard_summary.py.\n")
    print(
        "| model | arm | runs | pass@1 | pass after repair | mean rounds to green "
        "| out tok/run | in tok/run |"
    )
    print("|---|---|---:|---:|---:|---:|---:|---:|")
    for m, rs in recs.items():
        for arm in ("py", "yag", "yn"):
            x = [r for r in rs if r["arm"] == arm]
            n = len(x)
            p1 = sum(r["hidden_first"]["ok"] for r in x)
            fin = sum(r["hidden_final"]["ok"] for r in x)
            rounds = sum(r.get("rounds_to_green") or 0 for r in x) / n
            out_tok, in_tok = (
                sum(r["tokens"][p][k] for r in x for p in ("spec", "body")) / n
                for k in ("out", "in")
            )
            print(
                f"| {m} | {arm} | {n} | {p1} ({100 * p1 / n:.1f}%) | {fin} ({100 * fin / n:.1f}%) "
                f"| {rounds:.2f} | {out_tok:.0f} | {in_tok:.0f} |"
            )
    print("\nPaired first-reply sign test per task and seed (exact, two-sided), arm vs py:\n")
    print("| model | arm | arm only | py only | p |")
    print("|---|---|---:|---:|---:|")
    for m, rs in recs.items():
        key = collections.defaultdict(dict)
        for r in rs:
            key[(r["task"], r["_seed"])][r["arm"]] = r["hidden_first"]["ok"]
        for arm in ("yag", "yn"):
            wa = wp = 0
            for v in key.values():
                if arm in v and "py" in v:
                    wa += v[arm] and not v["py"]
                    wp += v["py"] and not v[arm]
            print(f"| {m} | {arm} | {wa} | {wp} | {sign_p(wa, wp):.4f} |")
    cost = collections.defaultdict(lambda: [0, 0, 0, 0.0])
    for line in a.ledger.read_text().splitlines():
        r = json.loads(line)
        c = cost[r["model"]]
        c[0] += 1
        c[1] += r["in"]
        c[2] += r["out"]
        c[3] += r["cost"]
    print(
        "\nSpend (OpenRouter ledger):\n\n"
        "| model | calls | in tok | out tok | USD |\n|---|---:|---:|---:|---:|"
    )
    for m, c in cost.items():
        print(f"| {m} | {c[0]} | {c[1]} | {c[2]} | {c[3]:.2f} |")
    print(f"| total | | | | {sum(c[3] for c in cost.values()):.2f} |")


if __name__ == "__main__":
    main()
