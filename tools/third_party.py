"""Generate THIRD_PARTY.md: licenses and notices of every crate linked into the `yan` binary.

third_party.py            write THIRD_PARTY.md
third_party.py --check    exit 1 when THIRD_PARTY.md is stale (Cargo.lock changed)

Scope: normal (non-dev, non-build) dependencies of yan-cli, from `cargo metadata --locked`.
License text is taken from the crate's own LICENSE/COPYING/NOTICE files, identical texts are merged.
"""

import argparse
import json
import subprocess
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

Package = dict[str, Any]

OUT = Path("THIRD_PARTY.md")
ROOT_PACKAGE = "yan-cli"
NOTICE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")


def metadata() -> Package:
    cmd = [
        "cargo", "metadata", "--locked", "--format-version", "1",
        "--filter-platform", "x86_64-unknown-linux-gnu",
    ]  # fmt: skip
    out = subprocess.run(cmd, capture_output=True, check=True, text=True).stdout
    meta: Package = json.loads(out)
    return meta


def linked(meta: Package) -> list[Package]:
    by_id = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(p["id"] for p in meta["packages"] if p["name"] == ROOT_PACKAGE)
    seen, stack = set(), [root]
    while stack:
        cur = stack.pop()
        if cur in seen:
            continue
        seen.add(cur)
        for dep in nodes[cur]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    return sorted(
        (by_id[i] for i in seen if by_id[i]["source"] is not None),
        key=lambda p: (p["name"], p["version"]),
    )


def notice_files(pkg: Package) -> list[Path]:
    root = Path(pkg["manifest_path"]).parent
    files = [
        f for f in root.iterdir() if f.is_file() and f.name.upper().startswith(NOTICE_PREFIXES)
    ]
    return sorted(files)


def render(pkgs: list[Package]) -> str:
    texts: dict[str, list[str]] = defaultdict(list)
    lines = [
        "# Third-party software",
        "",
        "The `yan` binary and `libyan_rt.a` link the crates below. Each keeps its own license.",
        "Generated by `tools/third_party.py` from `Cargo.lock`; do not edit.",
        "",
        "## Crates",
        "",
        "| Crate | Version | License |",
        "|---|---|---|",
    ]
    for p in pkgs:
        lines.append(f"| {p['name']} | {p['version']} | {p['license'] or 'see source'} |")
        for f in notice_files(p):
            texts[f.read_text(errors="replace").strip()].append(f"{p['name']} {p['version']}")
    lines += ["", "## License and notice texts", ""]
    for text, owners in sorted(texts.items(), key=lambda kv: kv[1][0]):
        lines += ["### Used by " + ", ".join(owners), "", "```text", text, "```", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(linked(metadata()))
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale: run `uv run python tools/third_party.py`", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
