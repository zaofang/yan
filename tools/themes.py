"""Editor and terminal themes from site/brand/tokens.json (Workshop Standard L10, L12).

uv run python -m tools.themes          write editors/themes/
uv run python -m tools.themes --check  exit 1 if a theme is out of date

Change the tokens, not the generated files.
"""

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "site/brand/tokens.json"
OUT = ROOT / "editors/themes"
NAMES = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
HEADER = "Generated by tools/themes.py from site/brand/tokens.json; do not edit."


def vscode(mode: str, t: dict[str, Any]) -> str:
    s, a = t["syntax"], t["ansi"]
    scopes = [
        ("comment", s["comment"], "italic"),
        ("keyword, storage", s["keyword"], ""),
        ("entity.name.type, support.type", s["type"], ""),
        ("string, constant.character", s["string"], ""),
        ("constant.numeric, constant.language", s["number"], ""),
        ("entity.name.function", t["text"], ""),
        ("invalid", t["error"], ""),
    ]
    colors = {
        "editor.background": t["bg"],
        "editor.foreground": t["text"],
        "editorCursor.foreground": t["accent"],
        "editorLineNumber.foreground": s["comment"],
        "editorLineNumber.activeForeground": t["text"],
        "editor.selectionBackground": t["border"],
        "editorWidget.background": t["surface"],
        "editorError.foreground": t["error"],
        "editorWarning.foreground": t["warning"],
        "editorInfo.foreground": t["info"],
        "focusBorder": t["accent"],
        "button.background": t["accent"],
        "button.foreground": t["on-accent"],
        "sideBar.background": t["surface"],
        "panel.border": t["border"],
        "terminal.background": t["bg"],
        "terminal.foreground": t["text"],
    }
    for n in NAMES:
        cap = n.capitalize()
        colors[f"terminal.ansi{cap}"] = a[n]
        colors[f"terminal.ansiBright{cap}"] = a[f"bright-{n}"]
    theme = {
        "$comment": HEADER,
        "name": f"Yan {mode.capitalize()}",
        "type": mode,
        "colors": colors,
        "tokenColors": [
            {"scope": sc, "settings": {"foreground": c, **({"fontStyle": f} if f else {})}}
            for sc, c, f in scopes
        ],
    }
    return json.dumps(theme, indent=2, ensure_ascii=False) + "\n"


def ghostty(t: dict[str, Any]) -> str:
    a = t["ansi"]
    order = NAMES + [f"bright-{n}" for n in NAMES]
    lines = [f"# {HEADER}"]
    lines += [f"palette = {i}={a[k]}" for i, k in enumerate(order)]
    lines += [
        f"background = {t['bg']}",
        f"foreground = {t['text']}",
        f"cursor-color = {t['accent']}",
        f"selection-background = {t['border']}",
        f"selection-foreground = {t['text']}",
    ]
    return "\n".join(lines) + "\n"


def themes(tokens: dict[str, Any]) -> dict[str, str]:
    out = {}
    for mode in ("dark", "light"):
        t = tokens[mode]
        out[f"yan-{mode}.color-theme.json"] = vscode(mode, t)
        out[f"yan-{mode}.ghostty"] = ghostty(t)
    return out


def main(argv: list[str]) -> int:
    want = themes(json.loads(TOKENS.read_text(encoding="utf-8")))
    if "--check" in argv:
        stale = [
            n
            for n, s in want.items()
            if not (OUT / n).is_file() or (OUT / n).read_text(encoding="utf-8") != s
        ]
        for n in stale:
            print(
                f"editors/themes/{n} is out of date: uv run python -m tools.themes", file=sys.stderr
            )
        return 1 if stale else 0
    OUT.mkdir(exist_ok=True)
    for n, s in want.items():
        (OUT / n).write_text(s, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
