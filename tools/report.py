"""Renders the weekly progress report from tools.status JSON (DL14: nothing here is typed by hand).

uv run python -m tools.report --status status.json [--github issues.json] [--out docs/reports]

status.json is `tools.status` output. issues.json is optional: {"open": N, "closed": N} issue counts
fetched by the caller (e.g. `gh issue list --json state`). The report is written to
docs/reports/<date>-progress.md; with no --out it is printed.
"""

import argparse
import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
LAWS = ROOT / "docs" / "development-laws.md"
LAW_ROW = re.compile(r"^\| (DL\d+) [^|]*\|.*\| (Gated|Enforced|Partial|None) \|$")


def laws(text: str) -> dict[str, int]:
    counts: dict[str, int] = {}
    for line in text.splitlines():
        m = LAW_ROW.match(line)
        if m:
            counts[m.group(2)] = counts.get(m.group(2), 0) + 1
    return counts


def pct(n: int, d: int) -> str:
    return f"{100 * n / d:.0f}%" if d else "n/a"


def render(
    status: dict[str, Any], law_counts: dict[str, int], issues: dict[str, int] | None
) -> str:
    commit, date = status["commit"], status["date"]
    conf, diff, debt = status["conformance"], status["differential"], status["spec_debt"]
    out = [
        f"# Progress report {date}",
        "",
        f"Main at `{commit[:7]}`, {date}. Generated by `tools.report` from `tools.status`; "
        "do not edit.",
        "",
        "## Conformance by milestone",
        "",
        "| Milestone | Cases | Pass | Fail | Skip |",
        "|---|---|---|---|---|",
    ]
    total = {"cases": 0, "pass": 0, "fail": 0, "skip": 0}
    for m, c in conf["milestones"].items():
        out.append(f"| {m} | {c['cases']} | {c['pass']} | {c['fail']} | {c['skip']} |")
        for k in total:
            total[k] += c[k]
    out += [
        f"| all | {total['cases']} | {total['pass']} | {total['fail']} | {total['skip']} |",
        "",
        f"Executors: {', '.join(conf['executors'])}. Passing: {total['pass']} of {total['cases']} "
        f"({pct(total['pass'], total['cases'])}) at `{commit[:7]}`, {date}.",
        "",
        "## Differential",
        "",
        f"Backends: {', '.join(diff['backends'])}. Programs: {diff['programs']}. Unexplained: "
        f"{diff['unexplained']}, allowlisted: {diff['allowlisted']}, refused: {diff['refused']}, "
        f"stale allowlist entries: {diff['stale']}. Figures from `tools.difftest` at "
        f"`{commit[:7]}`, {date}.",
        "",
        "## Spec debt",
        "",
        f"Rows without a case: {debt['rows_without_case']} of {debt['rows']} "
        f"({pct(debt['rows_without_case'], debt['rows'])}). Codes unimplemented: "
        f"{debt['codes_unimplemented']} of {debt['codes']}. At `{commit[:7]}`, {date}.",
        "",
        "## Laws",
        "",
        "Status counts from `docs/development-laws.md`: "
        + ", ".join(f"{k} {v}" for k, v in sorted(law_counts.items()))
        + f". At `{commit[:7]}`, {date}.",
    ]
    if issues:
        out += [
            "",
            "## Issues",
            "",
            f"Open: {issues['open']}, closed: {issues['closed']}. "
            f"Counted {date} at `{commit[:7]}`.",
        ]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--status", type=Path, required=True)
    ap.add_argument("--github", type=Path)
    ap.add_argument("--out", type=Path)
    args = ap.parse_args(argv)
    status = json.loads(args.status.read_text())
    issues = json.loads(args.github.read_text()) if args.github else None
    text = render(status, laws(LAWS.read_text(encoding="utf-8")), issues)
    if args.out:
        (args.out / f"{status['date']}-progress.md").write_text(text, encoding="utf-8")
    else:
        print(text, end="")


if __name__ == "__main__":
    main()
